/**
 * homeowner-wall.js — "Real Roofs. Real Neighbors." photo wall.
 *
 * Reusable, lazy-loaded photo grid driven by a JSON manifest
 * (/assets/data/homeowner-wall.json). The section stays HIDDEN until the
 * manifest has >= MIN_ENTRIES real photos, so it never renders an awkward
 * empty state on a fresh site — a job-close-out photo at every install feeds
 * it over time (DOPE handheld "No Big Deal!" signs + the completed-job
 * automation). No fabrication: every card is a real job photo Jo added.
 *
 * Manifest entry shape (image + alt required, the rest optional):
 *   { "image": "/assets/homeowner-wall/xxx.webp",
 *     "city":  "Milford, OH",
 *     "name":  "Sarah K.",          // first name + last initial only
 *     "alt":   "New GAF Timberline roof on a two-story home in Milford",
 *     "slug":  "milford-oh-full-tearoff-replacement-2026",  // → /our-work/<slug>
 *     "tag":   "Full Replacement" }
 *
 * NO PRICE ON THE TILES (Jo's call, 2026-09-20). The first cut of this carried
 * the price range in the caption. The live twelve span $100–$200 (an EPDM
 * inspection) to $73,000–$74,000 (the Milford commercial rebuild), and a
 * homepage tile reading $73,000 sets a very different expectation from the one
 * a homeowner pricing a re-roof should leave with. Prices still live on every
 * /our-work detail page and in their AggregateOffer schema — the wall's job is
 * to earn the click, and the CTA under it promises prices on the other side.
 * Pinned by tests/homeowner-wall-links.test.js so it is not re-added by
 * accident; if it ever should come back, that assertion is the place to argue.
 *
 * LINKING (2026-09-20). Every card used to be a dead thumbnail while
 * `.hw-card:hover` lifted it and deepened its shadow — the wall advertised a
 * click it could not deliver, sitting on top of 45 written project pages. A card
 * whose entry carries a valid slug is now wrapped in an <a> to its write-up.
 * Entries WITHOUT a slug still render as a plain figure, so an older manifest
 * (or a future non-project photo) degrades to exactly the previous behaviour
 * instead of vanishing or emitting href="/our-work/undefined".
 *
 * The href is built from the slug, so the slug is re-validated HERE against the
 * same kebab-case shape scripts/build-projects.mjs enforces — the renderer must
 * not trust the manifest to have been generated by that script. Anything else
 * renders unlinked rather than being escaped into an href.
 *
 * Extensionless on purpose: cleanUrls is on, so /our-work/<slug>.html would cost
 * a 301 on every card click.
 *
 * Zero layout shift: every <img> ships explicit width/height (the grid cell is
 * a fixed 4:3 box), loading="lazy", decoding="async". Mount points: any element
 * with id="homeowner-wall" (homepage + area pages reuse the same component).
 */
(function () {
  'use strict';

  var MIN_ENTRIES = 3;               // hide entirely below this — no thin walls
  var MAX_ENTRIES = 12;              // cap the grid; newest first
  var MANIFEST = '/assets/data/homeowner-wall.json';
  // Mirrors SLUG_RE in scripts/build-projects.mjs.
  var SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

  function esc(s) {
    return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
      .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  function valid(e) {
    return e && typeof e === 'object' && e.image && e.alt &&
      /^\/assets\/[\w./-]+\.(webp|jpg|jpeg|png)$/i.test(String(e.image));
  }

  function render(mount, items) {
    var grid = items.slice(0, MAX_ENTRIES).map(function (e) {
      // City, then what the job WAS. Each part is independently optional.
      // Price is deliberately absent — see the header note.
      var cap = [e.name, e.city, e.tag].filter(Boolean).map(esc).join(' · ');
      var body = '<img class="hw-img" src="' + esc(e.image) + '" alt="' + esc(e.alt) + '"'
        + ' width="400" height="300" loading="lazy" decoding="async">'
        + (cap ? '<figcaption class="hw-cap">' + cap + '</figcaption>' : '');
      var linkable = e.slug && SLUG_RE.test(String(e.slug));
      if (!linkable) return '<figure class="hw-card">' + body + '</figure>';
      // The alt text already describes the photo, so the link needs its own
      // accessible name or a screen reader announces the whole alt as the
      // destination. City + tag is what a sighted user is clicking.
      var label = [e.city, e.tag].filter(Boolean).map(esc).join(' — ') || 'this project';
      return '<figure class="hw-card">'
        + '<a class="hw-link" href="/our-work/' + esc(e.slug) + '"'
        + ' aria-label="See the full write-up: ' + label + '">'
        + body
        + '</a></figure>';
    }).join('');
    mount.querySelector('.hw-grid').innerHTML = grid;
    mount.hidden = false;            // reveal only now that we have real content
    mount.removeAttribute('aria-hidden');
  }

  function init() {
    var mount = document.getElementById('homeowner-wall');
    if (!mount || !mount.querySelector('.hw-grid')) return; // no slot on this page
    fetch(MANIFEST, { cache: 'no-cache' })
      .then(function (r) { return r.ok ? r.json() : []; })
      .then(function (data) {
        var items = (Array.isArray(data) ? data : []).filter(valid);
        if (items.length >= MIN_ENTRIES) render(mount, items);
        // else: leave hidden — component is invisible on an under-filled manifest
      })
      .catch(function () { /* network/parse fail → stay hidden, never break the page */ });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
